#!/usr/bin/env Rscript
# Clean-package control: fails if anything from the national study in which
# these packages were first developed appears in the repository.
#
#   Rscript tools/check-clean.R                 scan the files that would be
#                                               published (tracked + untracked,
#                                               not ignored)
#   Rscript tools/check-clean.R --history       also scan every commit
#   --root=DIR                                  repository root (default: parent
#                                               of tools/)
#   --patterns=FILE                             deny-list (default:
#                                               tools/clean-package-patterns.txt)
#
# Not scanned, and said so in the output: the deny-list itself, binary files,
# and third-party files generated by 'renv' (renv.lock, renv/activate.R).
# Exit status: 0 clean, 1 findings.

source(file.path(
  dirname(normalizePath(sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1]))),
  "common.R"
))
args <- tool_args()
root <- normalizePath(if (is.null(args$root)) file.path(tool_dir(), "..") else args$root)
pat_file <- normalizePath(
  if (is.null(args$patterns)) file.path(tool_dir(), "clean-package-patterns.txt") else args$patterns
)

rules <- readLines(pat_file, encoding = "UTF-8", warn = FALSE)
rules <- rules[nzchar(trimws(rules)) & !startsWith(rules, "#")]
rules <- strsplit(rules, "\t", fixed = TRUE)
bad_rule <- lengths(rules) != 2
if (any(bad_rule)) {
  cat("check-clean: malformed rule(s) in", pat_file, "\n")
  quit(status = 1, save = "no")
}
labels <- vapply(rules, `[`, "", 1)
regex <- vapply(rules, `[`, "", 2)

files <- repo_files(root)
third_party <- c("renv.lock", "renv/activate.R")
excluded <- files %in% third_party |
  normalizePath(file.path(root, files)) == pat_file
scan <- files[!excluded]
binary <- vapply(file.path(root, scan), is_binary, logical(1))
text_files <- scan[!binary]

findings <- character()
for (f in text_files) {
  lines <- readLines(file.path(root, f), warn = FALSE, encoding = "UTF-8")
  lines <- iconv(lines, "UTF-8", "UTF-8", sub = "?")
  # the file name counts too
  lines <- c(lines, f)
  where <- c(seq_along(lines[-length(lines)]), 0L)
  for (i in seq_along(regex)) {
    hit <- grep(regex[i], lines, perl = TRUE)
    for (h in hit) {
      findings <- c(findings, sprintf(
        "  %s:%s: [%s] %s", f, if (where[h] == 0L) "name" else where[h], labels[i],
        substr(trimws(lines[h]), 1, 120)
      ))
    }
  }
}

n_history <- NA_integer_
history_note <- "history not scanned (use --history)"
if (isTRUE(args$history)) {
  old <- setwd(root)
  commits <- suppressWarnings(system2("git", c("rev-list", "--all"), stdout = TRUE,
                                      stderr = FALSE))
  n_history <- length(commits)
  if (n_history > 0) {
    rel_pat <- sub(paste0(root, "/"), "", pat_file, fixed = TRUE)
    spec <- c("--", ".", paste0(":!", c(rel_pat, third_party)))
    for (i in seq_along(regex)) {
      out <- suppressWarnings(system2(
        "git", c("grep", "-n", "-I", "-P", "-e", shQuote(regex[i]), commits, spec),
        stdout = TRUE, stderr = TRUE
      ))
      status <- attr(out, "status")
      if (!is.null(status) && status > 1) {
        findings <- c(findings, sprintf("  history: git grep failed for rule [%s]: %s",
                                        labels[i], paste(utils::head(out, 2), collapse = " ")))
      } else if (length(out)) {
        findings <- c(findings, sprintf("  history %s: [%s]", substr(out, 1, 160), labels[i]))
      }
    }
  }
  setwd(old)
  history_note <- sprintf("%d commit(s) of history scanned", n_history)
}

if (length(findings)) cat(unique(findings), sep = "\n")
finish(
  "check-clean", length(unique(findings)),
  sprintf(paste0("%d file(s) reviewed with %d rule(s); not scanned: %d excluded by name ",
                 "(deny-list, renv files), %d binary; %s"),
          length(text_files), length(regex), sum(excluded), sum(binary), history_note)
)
